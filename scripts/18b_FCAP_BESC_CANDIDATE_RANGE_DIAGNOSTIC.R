library(ggplot2)
library(here)

# ============================================================
# DIRECTORIES
# ============================================================

rds_dir <- here("data","Rdata")
out_dir <- here("outputs","mse","Besc_candidate_range")
fig_dir <- file.path(out_dir,"figures")
dir.create(out_dir,recursive=TRUE,showWarnings=FALSE)
