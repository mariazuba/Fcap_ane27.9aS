# ============================================================
# FCAP_BESC_CANDIDATE_RANGE_DIAGNOSTIC.R
# Diagnostic for candidate Besc range
# Probabilistic Fcap + Besc management procedure
# Anchovy 9a South
#
# Purpose:
#   Characterise the biological and operational implications
#   of alternative escapement biomass thresholds before the
#   closed-loop MSE.
#
# This script DOES NOT select an optimal Besc.
# It defines and characterises a plausible candidate range.
#
# The diagnostic considers:
#   1. Besc relative to stock-specific biomass reference points.
#   2. Alternative reference-point values examined at WKBANSP.
#   3. Expected forecast SSB required to satisfy:
#
#      P(SSBforecast < Besc) <= alpha
#
#      equivalently:
#
#      Q_alpha(SSBforecast) >= Besc
#
#   4. Three forecast-uncertainty scenarios:
#      S0 = deterministic forecast
#      S1 = current assessment uncertainty
#      S2 = contemporary bootstrap uncertainty
#
# No FLBEIA simulation is run here.
# ============================================================

rm(list=ls())

