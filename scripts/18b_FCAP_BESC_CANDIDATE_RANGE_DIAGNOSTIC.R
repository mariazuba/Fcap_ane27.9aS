settings <- list(Blim=Blim,Bpa=Bpa,B0_WKBANSP=B0_WKBANSP,Bloss_WKBANSP=Bloss_WKBANSP,alpha=alpha,z_alpha=z_alpha,Besc_candidates=Besc_candidates,Besc_grid=Besc_grid)
outputs <- list(settings=settings,reference_points=reference_points,forecast_CV_summary=forecast_CV_summary,CV_S1=CV_S1,CV_S2=CV_S2,Besc_scale=Besc_scale,Besc_context=Besc_context,diagnostic=diagnostic,diagnostic_S2_raw=diagnostic_S2_raw,candidate_diagnostic=candidate_diagnostic,candidate_table=candidate_table,candidate_buffer=candidate_buffer,candidate_relative=candidate_relative,uncertainty_multiplier=uncertainty_multiplier)

saveRDS(outputs,file.path(out_dir,"BESC_candidate_range_diagnostic.rds"))

