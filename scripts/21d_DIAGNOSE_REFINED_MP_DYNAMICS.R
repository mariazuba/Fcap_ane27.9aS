make_historical_summary <- function(dat){
  
  out <- dat %>%
    filter(is.finite(value)) %>%
    group_by(year) %>%
    summarise(
      median=median(value),
      p05=quantile(value,0.05),
      p95=quantile(value,0.95),
      .groups="drop"
    )
  
  out
}

