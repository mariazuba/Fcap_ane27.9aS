add_global_map <- function(dat,map_b){
  
  out <- dat %>%mutate(iter_local=as.integer(as.character(iter))) %>%
    left_join(map_b %>%select(iter_local,iter1000,om,replicate),by="iter_local")
  
  stopifnot(!anyNA(out$iter1000))
  stopifnot(!anyNA(out$om))
  stopifnot(!anyNA(out$replicate))
  
  out
}


standardise_dynamic <- function(x,map_b,proj_years){
  
  out <- as.data.frame(x) %>%
    rename(value=data) %>%
    mutate(year=as.integer(as.character(year))) %>%
    add_global_map(map_b) %>%
    filter(year %in% proj_years) %>%
    transmute(year,iter1000,om,replicate,value)
  
  out
}


standardise_series <- function(x,map_b,years){
  
  out <- as.data.frame(x) %>%
    rename(value=data) %>%
    mutate(year=as.integer(as.character(year))) %>%
    add_global_map(map_b) %>%
    filter(year %in% years) %>%
    transmute(year,iter1000,om,replicate,value)
  
  out
}


# ============================================================
# 4. DIAGNOSE ONE CANDIDATE MP ----
# ============================================================

diagnose_candidate_MP <- function(scenario_row){
  
  scenario_number <- scenario_row$scenario_number[[1]]
  scenario_id <- scenario_row$scenario_id[[1]]
  Fcap <- scenario_row$Fcap[[1]]
  Besc <- scenario_row$Besc[[1]]
  Blim <- scenario_row$Blim[[1]]
  Bpa <- scenario_row$Bpa[[1]]
  first_proj <- scenario_row$first_projection_year[[1]]
  last_proj <- scenario_row$last_projection_year[[1]]
  proj_years <- first_proj:last_proj
  
  cat("\n============================================================\n")
  cat("SCENARIO:",scenario_number,"\n")
  cat("ID:",scenario_id,"\n")
  cat("Fcap:",Fcap,"| Besc:",Besc,"\n")
  cat("============================================================\n")
  
  
  # ==========================================================
  # 4.1 INPUT FILES
  # ==========================================================
  
  mp_dir <- file.path(scenario_root,scenario_id)
  mp_files <- file.path(mp_dir,sprintf("block_%02d.rds",block_ids))
  map_files <- file.path(mp_dir,sprintf("block_%02d_map.csv",block_ids))
  
  if(!dir.exists(mp_dir)){stop("Scenario directory not found: ",mp_dir)}
  if(!all(file.exists(mp_files))){stop("Missing RDS blocks for scenario ",scenario_number)}
  if(!all(file.exists(map_files))){stop("Missing map files for scenario ",scenario_number)}
  
  # ==========================================================
  # 4.2 VALIDATE COMPLETE ITERATION MAP
  # ==========================================================
  
  iteration_maps <- map_dfr(
    block_ids,
    ~read.csv(map_files[.x],stringsAsFactors=FALSE) %>%
      mutate(block=.x)
  )
  
  stopifnot(length(block_ids)==expected_blocks)
  stopifnot(nrow(iteration_maps)==expected_trajectories)
  stopifnot(n_distinct(iteration_maps$iter1000)==expected_trajectories)
  stopifnot(n_distinct(iteration_maps$om)==expected_OMs)
  stopifnot(all(table(iteration_maps$om)==expected_replicates))
  stopifnot(all(sort(unique(iteration_maps$replicate))==1:expected_replicates))
  stopifnot(!anyDuplicated(iteration_maps[,c("om","replicate")]))
  
  
  # ==========================================================
  # 4.3 EXTRACT ONE BLOCK
  # ==========================================================
  
  extract_MP_block <- function(block_id){
    
    OM_b <- readRDS(mp_files[block_id])
    map_b <- read.csv(map_files[block_id],stringsAsFactors=FALSE)
    
    stopifnot(nrow(map_b)==expected_block_size)
    
    biol <- OM_b$biols$ANE
    cobj <- OM_b$fleets$SEINE@metiers$ALL@catches$ANE
    
    R_b <- standardise_dynamic(biol@n["0",,,"3",,],map_b,proj_years)
    Mat <- predict(biol@mat)
    SSB_q2 <- quantSums(biol@n[,,,"2",,] *biol@wt[,,,"2",,] *Mat[,,,"2",,])
    B_b <- standardise_dynamic(SSB_q2,map_b,proj_years)
    C_ann <- seasonSums(quantSums(cobj@landings))
    C_b <- standardise_dynamic(C_ann,map_b,proj_years)
    TAC_b <- standardise_dynamic(OM_b$advice$TAC["ANE",,,,,],map_b,proj_years)
    Fadv_b <- standardise_dynamic(OM_b$advice$Fadv["ANE",,,,,],map_b,proj_years)
    R_hist_b <- standardise_series(biol@n["0",,,"3",,],map_b,historical_years)
    SSB_hist_q2 <- quantSums(biol@n[,,,"2",,] *biol@wt[,,,"2",,] *Mat[,,,"2",,])
    B_hist_b <- standardise_series(SSB_hist_q2,map_b,historical_years)
    C_hist_ann <- seasonSums(quantSums(cobj@landings))
    C_hist_b <- standardise_series(C_hist_ann,map_b,historical_years)
    TAC_hist_b <- standardise_series(OM_b$advice$TAC["ANE",,,,,],map_b,historical_years)
    Fadv_hist_b <- standardise_series(OM_b$advice$Fadv["ANE",,,,,],map_b,historical_years)
    
    list(
      R=R_b,
      SSB=B_b,
      Catch=C_b,
      TAC=TAC_b,
      Fadv=Fadv_b,
      R_hist=R_hist_b,
      SSB_hist=B_hist_b,
      Catch_hist=C_hist_b,
      TAC_hist=TAC_hist_b,
      Fadv_hist=Fadv_hist_b)
  }
  
  
  # ==========================================================
  # 4.4 EXTRACT COMPLETE CLOSED-LOOP ENSEMBLE
  # ==========================================================
  
  MP_blocks <- map(block_ids,extract_MP_block)
  
  R_MP <- map_dfr(MP_blocks,"R")
  B_MP <- map_dfr(MP_blocks,"SSB")
  C_MP <- map_dfr(MP_blocks,"Catch")
  TAC_MP <- map_dfr(MP_blocks,"TAC")
  Fadv_MP <- map_dfr(MP_blocks,"Fadv")
  R_hist_MP <- map_dfr(MP_blocks,"R_hist")
  B_hist_MP <- map_dfr(MP_blocks,"SSB_hist")
  C_hist_MP <- map_dfr(MP_blocks,"Catch_hist")
  TAC_hist_MP <- map_dfr(MP_blocks,"TAC_hist")
  Fadv_hist_MP <- map_dfr(MP_blocks,"Fadv_hist")
  
  rm(MP_blocks)
  
  gc(verbose=FALSE)
  
  expected_rows <- expected_trajectories*length(proj_years)
  
  stopifnot(nrow(R_MP)==expected_rows)
  stopifnot(nrow(B_MP)==expected_rows)
  stopifnot(nrow(C_MP)==expected_rows)
  stopifnot(nrow(TAC_MP)==expected_rows)
  stopifnot(nrow(Fadv_MP)==expected_rows)
  
  
  # ==========================================================
  # 4.5 BUILD COMPLETE YEAR × TRAJECTORY DATASET
  # ==========================================================
  
  dynamics <- B_MP %>%
    rename(SSB=value) %>%
    left_join(R_MP %>%rename(R=value),by=c("year","iter1000","om","replicate")) %>%
    left_join(C_MP %>%rename(Catch=value),by=c("year","iter1000","om","replicate")) %>%
    left_join(TAC_MP %>%rename(TAC=value),by=c("year","iter1000","om","replicate")) %>%
    left_join(
      Fadv_MP %>%
        rename(Fadv=value),
      by=c("year","iter1000","om","replicate")
    ) %>%
    arrange(iter1000,year)
  
  stopifnot(nrow(dynamics)==expected_rows)
  
  stopifnot(!anyNA(dynamics$SSB))
  stopifnot(!anyNA(dynamics$R))
  stopifnot(!anyNA(dynamics$Catch))
  stopifnot(!anyNA(dynamics$TAC))
  stopifnot(!anyNA(dynamics$Fadv))
  
  stopifnot(all(is.finite(dynamics$SSB)))
  stopifnot(all(is.finite(dynamics$R)))
  stopifnot(all(is.finite(dynamics$Catch)))
  stopifnot(all(is.finite(dynamics$TAC)))
  stopifnot(all(is.finite(dynamics$Fadv)))
  
  stopifnot(all(dynamics$SSB>=0))
  stopifnot(all(dynamics$R>=0))
  stopifnot(all(dynamics$Catch>=0))
  stopifnot(all(dynamics$TAC>=0))
  stopifnot(all(dynamics$Fadv>=0))
  stopifnot(all(dynamics$Fadv<=Fcap+tol_F))
  
  
  # ==========================================================
  # 4.6 DEFINE DIAGNOSTIC STATES
  # ==========================================================
  
  dynamics <- dynamics %>%
    group_by(iter1000,om,replicate) %>%
    arrange(year,.by_group=TRUE) %>%
    mutate(
      below_Blim=SSB<Blim,
      below_Bpa=SSB<Bpa,
      closed=Fadv<=tol_F,
      TAC_zero=TAC<=tol_TAC,
      previous_closed=lag(closed,default=FALSE),
      closure_start=closed & !previous_closed,
      reopening=!closed & previous_closed
    ) %>%
    ungroup()
  
  
  # ==========================================================
  # 4.7 ANNUAL CLOSED-LOOP DIAGNOSTICS
  # ==========================================================
  
  annual_summary <- dynamics %>%
    group_by(year) %>%
    summarise(
      SSB_median=median(SSB),
      SSB_p05=quantile(SSB,0.05),
      SSB_p95=quantile(SSB,0.95),
      SSB_min=min(SSB),
      R_median=median(R),
      R_p05=quantile(R,0.05),
      R_p95=quantile(R,0.95),
      Catch_median=median(Catch),
      Catch_p05=quantile(Catch,0.05),
      Catch_p95=quantile(Catch,0.95),
      TAC_median=median(TAC),
      TAC_p05=quantile(TAC,0.05),
      TAC_p95=quantile(TAC,0.95),
      Fadv_median=median(Fadv),
      Fadv_p05=quantile(Fadv,0.05),
      Fadv_p95=quantile(Fadv,0.95),
      P_Blim=mean(below_Blim),
      P_Bpa=mean(below_Bpa),
      P_closed=mean(closed),
      .groups="drop"
    ) %>%
    mutate(
      scenario_number=scenario_number,
      scenario_id=scenario_id,
      Fcap=Fcap,
      Besc=Besc,
      Blim=Blim,
      Bpa=Bpa,
      .before=1
    )
  
  # ==========================================================
  # HCR OPERATING-STATE DIAGNOSTIC
  # ==========================================================
  #
  # Each year × trajectory is classified according to the
  # management advice produced by the HCR.
  #
  # closed:
  #   Fadv approximately zero.
  #
  # restricted:
  #   Fadv is positive but lower than Fcap.
  #
  # at_Fcap:
  #   Fadv is approximately equal to Fcap.
  #
  # This is a diagnostic classification and is not used as an
  # MP acceptance or selection criterion.
  # ==========================================================
  
  HCR_state_summary <- dynamics %>%
    mutate(
      HCR_state=case_when(
        Fadv<=tol_F ~ "closed",
        abs(Fadv-Fcap)<=tol_F ~ "at_Fcap",
        Fadv>tol_F & Fadv<Fcap-tol_F ~ "restricted",
        TRUE ~ "other")) %>%
    count(HCR_state,name="n") %>%
    complete(HCR_state=c("closed","restricted","at_Fcap","other"),fill=list(n=0)) %>%
    mutate(
      proportion=n/sum(n),
      scenario_number=scenario_number,
      scenario_id=scenario_id,
      Fcap=Fcap,
      Besc=Besc,
      .before=1)
  
  HCR_state_annual <- dynamics %>%
    mutate(
      HCR_state=case_when(
        Fadv<=tol_F ~ "closed",
        abs(Fadv-Fcap)<=tol_F ~ "at_Fcap",
        Fadv>tol_F & Fadv<Fcap-tol_F ~ "restricted",
        TRUE ~ "other")) %>%
    count(year,HCR_state,name="n") %>%
    complete(
      year=proj_years,
      HCR_state=c("closed","restricted","at_Fcap","other"),
      fill=list(n=0)) %>%
    group_by(year) %>%
    mutate(proportion=n/sum(n)) %>%
    ungroup() %>%
    mutate(
      scenario_number=scenario_number,
      scenario_id=scenario_id,
      Fcap=Fcap,
      Besc=Besc,
      .before=1)
  
  # ==========================================================
  # CLOSURE PERSISTENCE AND SWITCHING DIAGNOSTIC
  # ==========================================================
  #
  # Quantifies how persistent closures are and how frequently
  # trajectories switch between open and closed states.
  #
  # This is a diagnostic description of HCR behaviour and is
  # not used as an MP acceptance or selection criterion.
  # ==========================================================
  
  closure_runs <- dynamics %>%
    arrange(iter1000,year) %>%
    group_by(iter1000,om,replicate) %>%
    mutate(
      closure_run_id=cumsum(closed!=lag(closed,default=first(closed)))
    ) %>%
    filter(closed) %>%
    group_by(iter1000,om,replicate,closure_run_id) %>%
    summarise(
      start_year=min(year),
      end_year=max(year),
      duration=end_year-start_year+1,
      .groups="drop"
    )
  
  closure_persistence_summary <- tibble(
    scenario_number=scenario_number,
    scenario_id=scenario_id,
    Fcap=Fcap,
    Besc=Besc,
    n_closure_runs=nrow(closure_runs),
    mean_closure_duration=if(nrow(closure_runs)>0) mean(closure_runs$duration) else 0,
    median_closure_duration=if(nrow(closure_runs)>0) median(closure_runs$duration) else 0,
    p95_closure_duration=if(nrow(closure_runs)>0) as.numeric(quantile(closure_runs$duration,0.95)) else 0,
    max_closure_duration=if(nrow(closure_runs)>0) max(closure_runs$duration) else 0
  )
  
  switching_summary <- dynamics %>%
    arrange(iter1000,year) %>%
    group_by(iter1000,om,replicate) %>%
    summarise(
      n_closure_events=sum(closure_start),
      n_reopening_events=sum(reopening),
      n_switches=n_closure_events+n_reopening_events,
      .groups="drop"
    ) %>%
    summarise(
      mean_closure_events=mean(n_closure_events),
      median_closure_events=median(n_closure_events),
      max_closure_events=max(n_closure_events),
      mean_reopening_events=mean(n_reopening_events),
      median_reopening_events=median(n_reopening_events),
      max_reopening_events=max(n_reopening_events),
      mean_switches=mean(n_switches),
      median_switches=median(n_switches),
      max_switches=max(n_switches)
    ) %>%
    mutate(
      scenario_number=scenario_number,
      scenario_id=scenario_id,
      Fcap=Fcap,
      Besc=Besc,
      .before=1
    )
  
  # ==========================================================
  # 4.8 TRAJECTORY-LEVEL DIAGNOSTICS
  # ==========================================================
  
  trajectory_summary <- dynamics %>%
    group_by(iter1000,om,replicate) %>%
    summarise(
      min_SSB=min(SSB),
      year_min_SSB=year[which.min(SSB)],
      mean_SSB=mean(SSB),
      median_SSB=median(SSB),
      min_R=min(R),
      max_R=max(R),
      mean_Catch=mean(Catch),
      max_Catch=max(Catch),
      mean_TAC=mean(TAC),
      max_TAC=max(TAC),
      mean_Fadv=mean(Fadv),
      max_Fadv=max(Fadv),
      ever_below_Blim=any(below_Blim),
      ever_below_Bpa=any(below_Bpa),
      n_years_below_Blim=sum(below_Blim),
      n_years_below_Bpa=sum(below_Bpa),
      ever_closed=any(closed),
      n_years_closed=sum(closed),
      n_closure_events=sum(closure_start),
      n_reopening_events=sum(reopening),
      .groups="drop"
    ) %>%
    mutate(
      scenario_number=scenario_number,
      scenario_id=scenario_id,
      Fcap=Fcap,
      Besc=Besc,
      .before=1
    )
  
  
  # ==========================================================
  # 4.9 MINIMUM-SSB EVENTS
  # ==========================================================
  #
  # One row is retained per trajectory at the year of minimum
  # SSB. This allows the management response associated with
  # the lowest stock state to be inspected directly.
  # ==========================================================
  
  minimum_SSB_events <- dynamics %>%
    group_by(iter1000,om,replicate) %>%
    slice_min(order_by=SSB,n=1, with_ties=FALSE) %>%
    ungroup() %>%
    mutate(
      scenario_number=scenario_number,
      scenario_id=scenario_id,
      Fcap=Fcap,
      Besc=Besc,
      .before=1)
  
  
  # ==========================================================
  # 4.10 BLIM CROSSING EVENTS
  # ==========================================================
  
  Blim_crossing_events <- dynamics %>%
    group_by(iter1000,om,replicate) %>%
    arrange(year,.by_group=TRUE) %>%
    mutate(previous_below_Blim=lag(below_Blim,default=FALSE)) %>%
    filter(below_Blim & !previous_below_Blim) %>%
    ungroup() %>%
    mutate(
      scenario_number=scenario_number,
      scenario_id=scenario_id,
      Fcap=Fcap,
      Besc=Besc,
      .before=1)
  
  # ==========================================================
  # 4.11 CLOSURE EVENTS
  # ==========================================================
  
  closure_events <- dynamics %>%
    filter(closure_start) %>%
    mutate(
      scenario_number=scenario_number,
      scenario_id=scenario_id,
      Fcap=Fcap,
      Besc=Besc,
      .before=1)
  
  # ==========================================================
  # 4.12 REOPENING EVENTS
  # ==========================================================
  
  reopening_events <- dynamics %>%
    filter(reopening) %>%
    mutate(
      scenario_number=scenario_number,
      scenario_id=scenario_id,
      Fcap=Fcap,
      Besc=Besc,
      .before=1)
  
  # ==========================================================
  # 4.13 EXTREME TRAJECTORIES FOR LATER INSPECTION
  # ==========================================================
  #
  # These trajectories are retained as diagnostic cases.
  # Their identification does not imply failure of the MP.
  # ==========================================================
  
  extreme_trajectories <- bind_rows(
    trajectory_summary %>%
      arrange(min_SSB) %>%
      slice_head(n=10) %>%
      mutate(diagnostic_case="lowest_min_SSB"),
    trajectory_summary %>%
      arrange(desc(max_Fadv)) %>%
      slice_head(n=10) %>%
      mutate(diagnostic_case="highest_Fadv"),
    trajectory_summary %>%
      arrange(desc(max_TAC)) %>%
      slice_head(n=10) %>%
      mutate(diagnostic_case="highest_TAC"),
    trajectory_summary %>%
      arrange(desc(max_Catch)) %>%
      slice_head(n=10) %>%
      mutate(diagnostic_case="highest_Catch"),
    trajectory_summary %>%
      arrange(desc(n_years_closed)) %>%
      slice_head(n=10) %>%
      mutate(diagnostic_case="most_years_closed")) %>%
    distinct(scenario_number,iter1000,diagnostic_case,.keep_all=TRUE)
  
  
  # ==========================================================
  # 4.14 SCENARIO-LEVEL DYNAMIC SUMMARY
  # ==========================================================
  
  dynamic_summary <- trajectory_summary %>%
    summarise(
      scenario_number=first(scenario_number),
      scenario_id=first(scenario_id),
      Fcap=first(Fcap),
      Besc=first(Besc),
      n_trajectories=dplyr::n(),
      min_SSB=min(min_SSB),
      median_min_SSB=median(min_SSB),
      P_ever_Blim=mean(ever_below_Blim),
      P_ever_Bpa=mean(ever_below_Bpa),
      P_ever_closed=mean(ever_closed),
      mean_years_below_Blim=mean(n_years_below_Blim),
      mean_years_closed=mean(n_years_closed),
      max_years_closed=max(n_years_closed),
      total_closure_events=sum(n_closure_events),
      total_reopening_events=sum(n_reopening_events),
      max_Fadv=max(max_Fadv),
      max_TAC=max(max_TAC),
      max_Catch=max(max_Catch)
    )
  
  
  # ==========================================================
  # 4.15 HISTORICAL SERIES FOR WORKING DOCUMENT FIGURES
  # ==========================================================
  
  historical_summary <- list(
    R=R_hist_MP,
    SSB=B_hist_MP,
    Catch=C_hist_MP,
    TAC=TAC_hist_MP,
    Fadv=Fadv_hist_MP
  )
  
  # ==========================================================
  # 4.16 INTERNAL DIAGNOSTIC CHECKS
  # ==========================================================
  
  stopifnot(nrow(trajectory_summary)==expected_trajectories)
  stopifnot(nrow(minimum_SSB_events)==expected_trajectories)
  
  stopifnot(all(trajectory_summary$n_years_closed>=0))
  stopifnot(all(trajectory_summary$n_years_closed<=length(proj_years)))
  
  stopifnot(all(trajectory_summary$n_years_below_Blim>=0))
  stopifnot(all(trajectory_summary$n_years_below_Blim<=length(proj_years)))
  
  cat("Dynamic diagnostic completed\n")
  cat("Minimum SSB:",dynamic_summary$min_SSB,"t\n")
  cat("P ever below Blim:",dynamic_summary$P_ever_Blim,"\n")
  cat("P ever below Bpa:",dynamic_summary$P_ever_Bpa,"\n")
  cat("P ever closed:",dynamic_summary$P_ever_closed,"\n")
  cat("Closure events:",dynamic_summary$total_closure_events,"\n")
  cat("Reopening events:",dynamic_summary$total_reopening_events,"\n")
  
  
  # ==========================================================
  # 4.17 RETURN SCENARIO DIAGNOSTICS
  # ==========================================================
  
  list(
    summary=dynamic_summary,
    annual=annual_summary,
    trajectory=trajectory_summary,
    minimum_SSB=minimum_SSB_events,
    Blim_crossings=Blim_crossing_events,
    closures=closure_events,
    reopenings=reopening_events,
    extremes=extreme_trajectories,
    HCR_state=HCR_state_summary,
    HCR_state_annual=HCR_state_annual,
    closure_persistence=closure_persistence_summary,
    switching=switching_summary,
    historical=historical_summary
  )
}


