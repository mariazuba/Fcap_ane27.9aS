# ============================================================
# 21d_DIAGNOSE_REFINED_MP_DYNAMICS.R
# Closed-loop dynamic diagnostics for candidate Fcap-Besc MPs
#
# Stock / analysis:
#   European anchovy ane.27.9aS, Gulf of Cádiz
#   Shortcut MSE implemented in FLBEIA + FLasher
#
# Refined-grid adaptation:
#   This script diagnoses the definitive 28-MP refined grid.
#   refined_scenario_number is mapped internally to scenario_number
#   for downstream diagnostic code only; simulation directories are
#   still located by scenario_id. Existing FLBEIA outputs are not modified.
#
# Role in the workflow:
#
#   20_RUN_MP_SCENARIO_PROBABILISTIC.R
#                     |
#                     v
#   21_CHECK_MP_SCENARIO_PROBABILISTIC.R / 21c_CHECK_REFINED_NEW_MPS.R
#                     |
#                     v
#   21d_DIAGNOSE_REFINED_MP_DYNAMICS.R
#                     |
#                     v
#   22_EVALUATE_CANDIDATE_MPS.R
#
# Purpose:
#   Diagnose the biological and fishery dynamics generated by
#   the complete closed-loop MSE before formal MP performance
#   evaluation.
#
#   The script examines:
#
#     - recruitment in Q3;
#     - SSB in Q2;
#     - annual realised catch;
#     - TAC advice;
#     - F advice;
#     - SSB crossings below Bpa and Blim;
#     - HCR response around low-stock states;
#     - closures and reopening;
#     - minimum SSB and associated management response;
#     - extreme values of SSB, recruitment, TAC, catch and Fadv.
#
#   Diagnostics are produced for all 28 refined candidate MPs and for
#   all 1000 trajectories per MP over 2025-2054.
#
# Inputs:
#   data/mse/scenarios/refined/candidate_MP_grid_refined.csv
#
#   data/mse/MP_runs/<scenario_id>/
#     block_XX.rds
#     block_XX_map.csv
#
# Outputs:
#   outputs/mse/diagnostics_refined/
#     21d_MP_dynamic_summary.csv
#     21d_MP_annual_diagnostics.csv
#     21d_MP_trajectory_diagnostics.csv
#     21d_MP_minimum_SSB_events.csv
#     21d_MP_Blim_crossing_events.csv
#     21d_MP_closure_events.csv
#     21d_MP_reopening_events.csv
#     21d_MP_extreme_trajectories.csv
#     21d_MP_dynamic_diagnostics.rds
#
# Working Document outputs:
#
#   Tables:
#     21d_WD_Table1_dynamic_summary.csv
#     21d_WD_Table2_annual_extremes.csv
#     21d_WD_Table3_extreme_trajectories.csv
#
#   Figures:
#     21d_WD_Figure1_recruitment_history_projection.png
#     21d_WD_Figure2_SSB_history_projection.png
#     21d_WD_Figure3_catch_history_projection.png
#     21d_WD_Figure4_TAC_history_projection.png
#     21d_WD_Figure5_Fadv_history_projection.png
#
# Important:
#   This is a diagnostic script.
#
#   It DOES NOT:
#     - rerun FLBEIA;
#     - modify the operating model;
#     - modify the management procedure;
#     - rank candidate MPs;
#     - select a preferred MP;
#     - define additional performance criteria;
#     - replace the performance evaluation in script 22.
#
#   Blim and Bpa crossings, closures, reopening and extreme
#   trajectories are diagnostic outputs and are not used here
#   as automatic acceptance or rejection criteria.
# ============================================================


